function variants(prefix: string, base: number, list: [string, number, number][]): ProductVariant[] {
  return list.map(([name, mod, stock], i) => ({
    id: `v${i + 1}`,
    name,
    priceModifier: mod,
    price: base + mod,
    stock,
    sku: `${prefix}-${i + 1}`,
  }));
}

