/*
 * Pedidos de EJEMPLO para que el resumen del panel tenga con qué mostrar números.
 * Son inventados (fechas fijas del 1/8 al 6/11/2026, generador con semilla fija para que
 * servidor y navegador den lo mismo). Se borran cuando la tienda tenga pedidos reales.
 */
function sampleOrders(): Order[] {
  let seed = 20261107;
  const rand = () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const pick = <T,>(list: T[]) => list[Math.floor(rand() * list.length)];
  const catalog = INITIAL_PRODUCTS.filter((p) => p.active && p.price > 0);
  const shipping: Order['shippingMethod'][] = ['pickup', 'pickup', 'pickup', 'moto_caba', 'correo_argentino'];
  const payments: Order['paymentMethod'][] = ['transferencia', 'mercadopago', 'mercadopago', 'mostrador'];
  const orders: Order[] = [];
  const start = Date.UTC(2026, 7, 1);
  let n = 1;
  for (let day = 0; day < 98; day++) {
    const date = new Date(start + day * 86_400_000);
    if (date.getUTCDay() === 0) continue; // domingo cerrado
    const count = Math.floor(rand() * 3) + (date.getUTCDay() === 6 ? 1 : 0);
    for (let k = 0; k < count; k++) {
      const lines = Math.floor(rand() * 2) + 1;
      const items = Array.from({ length: lines }, () => {
        const product = pick(catalog);
        const variant = product.variants?.length ? pick(product.variants) : undefined;
        const unitPrice = variant ? product.price + (variant.priceModifier ?? 0) : product.price;
        const quantity = rand() < 0.85 ? 1 : 2;
        return {
          productId: product.id,
          productName: product.name,
          productImage: product.images[0] ?? '',
          variantId: variant?.id,
          variantName: variant?.name,
          quantity,
          unitPrice,
          totalPrice: unitPrice * quantity,
        };
      });
      const shippingMethod = pick(shipping);
      const paymentMethod = shippingMethod === 'pickup' ? pick(payments) : pick(payments.filter((p) => p !== 'mostrador'));
      const shippingCost = shippingMethod === 'moto_caba' ? 3500 : shippingMethod === 'correo_argentino' ? 5800 : 0;
      const subtotal = items.reduce((sum, i) => sum + i.totalPrice, 0);
      const minutes = 12 * 60 + Math.floor(rand() * 9 * 60); // 9 a 18 h en Buenos Aires
      const daysAgo = 97 - day;
      orders.push({
        id: `ord-ej-${n}`,
        orderNumber: `EJ-${String(n).padStart(4, '0')}`,
        createdAt: new Date(date.getTime() + minutes * 60_000).toISOString(),
        customer: { fullName: `Cliente de ejemplo ${n}`, email: `ejemplo${n}@ejemplo.com`, phone: '1100000000' },
        items,
        subtotal,
        shippingMethod,
        shippingCost,
        paymentMethod,
        total: subtotal + shippingCost,
        status: daysAgo < 2 ? pick(['pendiente', 'en_preparacion'] as const) : rand() < 0.06 ? 'pendiente' : 'entregado',
        isSample: true,
      });
      n++;
    }
  }
  return orders.reverse();
}
